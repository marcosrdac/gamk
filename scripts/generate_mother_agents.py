#!/usr/bin/env python3
"""Generate the mother repository AGENTS.md from shared template + local extension."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEMPLATE = ROOT / "global/templates/project/AGENTS.md"
EXTENSIONS = ROOT / ".ai/templates/mother-AGENTS.extensions.md"
OUTPUT = ROOT / "AGENTS.md"
MARKER = "<!-- Generated by scripts/generate_mother_agents.py; edit the template and extensions, not this file. -->"


def generated_content() -> str:
    shared = TEMPLATE.read_text(encoding="utf-8").rstrip()
    mother = EXTENSIONS.read_text(encoding="utf-8").strip()
    return f"{shared}\n\n{MARKER}\n\n{mother}\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing if AGENTS.md is stale")
    args = parser.parse_args(argv)
    expected = generated_content()
    if args.check:
        try:
            current = OUTPUT.read_text(encoding="utf-8")
        except OSError as error:
            print(f"Cannot read generated file {OUTPUT}: {error}", file=sys.stderr)
            return 2
        if current != expected:
            print(f"{OUTPUT} is stale; run `python scripts/generate_mother_agents.py`.", file=sys.stderr)
            return 1
        print(f"{OUTPUT} is up to date.")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT} from {TEMPLATE.relative_to(ROOT)} + {EXTENSIONS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
